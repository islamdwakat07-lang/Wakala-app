package com.wakala.generator

fun clauseNumberWord(n: Int): String {
    val units = arrayOf(
        "", "واحد", "اثنان", "ثلاثة", "اربعة", "خمسة",
        "ستة", "سبعة", "ثمانية", "تسعة"
    )
    return when {
        n == 10 -> "عشرة"
        n == 11 -> "احد عشر"
        n == 12 -> "اثنا عشر"
        n in 13..19 -> "${units[n - 10]} عشر"
        n == 20 -> "عشرون"
        n in 21..29 -> "${units[n - 20]} وعشرون"
        n == 30 -> "ثلاثون"
        else -> n.toString()
    }
}

fun buildAgreementSaleSegments(d: AgreementSaleData): List<TextSegment> {
    val list = mutableListOf<TextSegment>()

    fun t(s: String) = list.add(TextSegment(s, false))
    fun v(s: String) = list.add(TextSegment(s, true))

    t("اتفاقية بيع\n\n")
    t("إنه في يوم الموافق ")
    v(d.dateText.ifBlank { "__/__/____" })
    t(" تم الاتفاق بين كل من:\n\n")

    t("الفريق الأول: ")
    v(d.party1Name)
    t("، حامل هوية رقم ")
    v(d.party1Id)
    t("، ومكان سكنه ")
    v(d.party1Residence)
    t(".\n\n")

    t("الفريق الثاني: ")
    v(d.party2Name)
    t("، حامل هوية رقم ")
    v(d.party2Id)
    t("، ومكان سكنه ")
    v(d.party2Residence)
    t(".\n\n")

    t("المقدمة:\n\n")

    t("حيث ان الفريق الاول يملك ويتصرف في ")
    v(d.ownershipDescription)
    t(" الارض رقم ")
    v(d.qitaaNumbers)
    t(" بحوض رقم ")
    v(d.hawzNumber)
    t(" من اراضي ")
    v(d.locationName)
    t(" قضاء ")
    v(d.qada)
    t(" (ويشار اليها فيما يلي بـ\"الارض الموصوفه اعلاه\").\n\n")

    t("وحيث ان الفريق الثاني يرغب بشراء ")
    v(d.party2WishDescription)
    t(" الارض الموصوفه اعلاه.\n\n")

    t("وحيث ان الفريق الاول يرغب في بيع ")
    v(d.party1SellDescription)
    t(" الارض الموصوفه اعلاه الى الفريق الثاني.\n\n")

    t("لذلك اتفق الطرفان على ما يلي:\n\n")

    t("اولا: تعتبر المقدمة اعلاه جزءا لا يتجزأ من هذا العقد.\n\n")

    t("ثانيا: باع الفريق الاول للفريق الثاني الارض الموصوفه اعلاه بالثمن الاجمالي والنهائي ")
    v(d.priceText)
    t(" يدفع على النحو المتفق عليه بين الطرفين.\n\n")

    t("ثالثا: يتم تسجيل هذا البيع لدى ")
    v(d.transferOffice)
    t(" ويتحمل الطرفان الرسوم كل حسب ما يخصه قانونا.\n\n")

    t("رابعا: في حال امتناع اي من الطرفين عن تنفيذ التزاماته الواردة في هذا العقد، يتحمل الطرف الممتنع غرامة مالية قدرها ")
    v(d.penaltyAmount)
    t(" دينار اردني للطرف الاخر، دون الاخلال بحقه بالمطالبة بالتنفيذ العيني.\n\n")

    t("خامسا: في حال نشوء اي خلاف حول تفسير او تنفيذ هذا العقد يرجع الطرفان الى محاكم ")
    v(d.courtName)
    t(" المختصة.\n\n")

    t("سادسا: حرر هذا العقد من ")
    v(d.pagesCount)
    t(" ووقع منه ")
    v(d.copiesCount)
    t(" نسخ متطابقة، احتفظ كل طرف بنسخة منها.\n\n")

    t("سابعا: يقر الفريق الاول بان الارض الموصوفه اعلاه خالية من اي رهن او حجز او دعوى او حق للغير، وانه المالك الشرعي والحقيقي لها.\n\n")

    t("ثامنا: يتم تسليم الارض الموصوفه اعلاه للفريق الثاني فور اتمام اجراءات التسجيل او على النحو المتفق عليه بين الطرفين.\n\n")

    t("تاسعا: يلتزم الفريق الاول بضمان التعرض والاستحقاق للفريق الثاني وفقا للقواعد العامة في القانون.\n\n")

    t("عاشرا: كل ما لم يرد عليه نص خاص في هذا العقد يخضع لاحكام القانون المعمول به.\n\n")

    t("حادي عشر: يعتبر هذا العقد ملزما لطرفيه وورثتهما وخلفهما القانوني من بعدهما.\n\n")

    d.extraClauses.forEachIndexed { index, clause ->
        val num = index + 12
        t("${clauseNumberWord(num)}: ")
        v(clause.ifBlank { "......................" })
        t("\n\n")
    }

    return list
}
